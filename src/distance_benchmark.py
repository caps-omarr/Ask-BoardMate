def cosine_similarity(u: np.ndarray, v: np.ndarray) -> float:
    """
    Compute Cosine Similarity between two 1D dense vectors:
    cos(theta) = (u . v) / (||u|| * ||v||)
    """
    norm_u = np.linalg.norm(u)
    norm_v = np.linalg.norm(v)
    if norm_u == 0 or norm_v == 0:
        return 0.0
    return float(np.dot(u, v) / (norm_u * norm_v))

def euclidean_distance(u: np.ndarray, v: np.ndarray) -> float:
    """
    Compute Euclidean (L2) Distance between two 1D dense vectors:
    L2 = sqrt(sum((u_i - v_i)^2))
    """
    return float(np.linalg.norm(u - v))

def dot_product(u: np.ndarray, v: np.ndarray) -> float:
    """
    Compute Inner Product / Dot Product between two 1D dense vectors:
    IP = sum(u_i * v_i)
    """
    return float(np.dot(u, v))

def run_distance_benchmarks():
    """
    Run mathematical distance metric benchmark (Cosine vs Euclidean vs Dot Product)
    over candidate boarding house embeddings generated by sentence-transformers.
    """
    from sentence_transformers import SentenceTransformer

    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    chunks_path = os.path.join(base_dir, "data", "processed_chunks.json")
    
    if not os.path.exists(chunks_path):
        raise FileNotFoundError(f"Processed chunks not found at {chunks_path}. Run preprocessing.py first.")

    with open(chunks_path, 'r', encoding='utf-8') as f:
        chunks = json.load(f)

    print("="*70)
    print(" VECTOR DISTANCE METRICS COMPARATIVE BENCHMARK (NumPy / SciPy) ")
    print("="*70)

    print("\n[1] Loading 'sentence-transformers/all-MiniLM-L6-v2'...")
    model = SentenceTransformer('sentence-transformers/all-MiniLM-L6-v2')
    doc_texts = [c["chunk_text"] for c in chunks]
    doc_embeddings = model.encode(doc_texts, show_progress_bar=False)

    test_queries = [
        "Female dorm near TPC main gate under 1500 pesos with free water",
        "Male boarding house with light and water included near campus",
        "Private room with aircon and wifi near Talibon Polytechnic College"
    ]

    for q_idx, query_text in enumerate(test_queries, 1):
        print("\n" + "-"*70)
        print(f"TEST QUERY #{q_idx}: '{query_text}'")
        print("-"*70)

        q_emb = model.encode(query_text)

        metrics_data = []

        for d_idx, (chunk, d_emb) in enumerate(zip(chunks, doc_embeddings)):
            cos_sim = cosine_similarity(q_emb, d_emb)
            l2_dist = euclidean_distance(q_emb, d_emb)
            dot_prod = dot_product(q_emb, d_emb)

            metrics_data.append({
                "name": chunk["name"],
                "rent_price": chunk["metadata"]["rent_price"],
                "allowed_genders": chunk["metadata"]["allowed_genders"],
                "cos_sim": cos_sim,
                "l2_dist": l2_dist,
                "dot_prod": dot_prod
            })

        # Sort top 5 by Cosine Similarity (Descending)
        top_cos = sorted(metrics_data, key=lambda x: x["cos_sim"], reverse=True)[:5]
        # Sort top 5 by L2 Distance (Ascending)
        top_l2 = sorted(metrics_data, key=lambda x: x["l2_dist"])[:5]
        # Sort top 5 by Dot Product (Descending)
        top_dot = sorted(metrics_data, key=lambda x: x["dot_prod"], reverse=True)[:5]

        print("\n[TOP 5 BY COSINE SIMILARITY (Higher is better)]")
        for i, item in enumerate(top_cos, 1):
            print(f"  {i}. {item['name']:<40} | Cosine: {item['cos_sim']:.4f} | Rent: ₱{item['rent_price']}")

        print("\n[TOP 5 BY EUCLIDEAN L2 DISTANCE (Lower is better)]")
        for i, item in enumerate(top_l2, 1):
            print(f"  {i}. {item['name']:<40} | L2 Dist: {item['l2_dist']:.4f} | Rent: ₱{item['rent_price']}")

        print("\n[TOP 5 BY DOT PRODUCT (Higher is better)]")
        for i, item in enumerate(top_dot, 1):
            print(f"  {i}. {item['name']:<40} | Dot Prod: {item['dot_prod']:.4f} | Rent: ₱{item['rent_price']}")

        # Verify ranking consistency between metrics
        names_cos = [x["name"] for x in top_cos]
        names_l2 = [x["name"] for x in top_l2]
        names_dot = [x["name"] for x in top_dot]

        is_identical = (names_cos == names_l2 == names_dot)
        print(f"\n>> RANKING CONSISTENCY ANALYSIS: Top-5 candidate rankings are 100% IDENTICAL across Cosine, L2, and Dot Product: {is_identical}")

    print("\n" + "="*70)
    print(" BENCHMARK EVALUATION COMPLETE ")
    print("="*70)

if __name__ == "__main__":
    run_distance_benchmarks()
